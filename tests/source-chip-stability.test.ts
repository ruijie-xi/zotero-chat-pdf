import { beforeEach, expect, it, vi } from "vitest";
import { ChatSession } from "../src/modules/chat-session";
const mocks = vi.hoisted(() => ({ state: null as any }));
vi.mock("../src/modules/panel-state", () => ({ getPanelState: () => mocks.state }));
vi.mock("../src/modules/chat-history", () => ({ saveSession: vi.fn(async () => {}) }));
import { refreshSourceChips } from "../src/modules/source-chips";
import { saveSession } from "../src/modules/chat-history";
let root: HTMLElement;
beforeEach(() => {
  vi.clearAllMocks();
  document.body.innerHTML = '<div id="chatpdf-root"><div id="chatpdf-source-chips"></div></div>';
  root = document.querySelector("#chatpdf-root")!;
  mocks.state = { session: new ChatSession(), windowId: "one", win: window, backgroundStreams: new Map(), chatInput: null };
});
const more = () => root.querySelector<HTMLButtonElement>('[data-action="source-menu"]')!;
it("adds a PDF ready for on-demand reading and keeps controls attached through refresh", () => {
  const source = mocks.state.session.addSource("PDF", "Paper", undefined, 1);
  refreshSourceChips(root);
  expect(source.status).toBe("ready");
  expect(root.querySelector(".chatpdf-chip-badge")?.textContent).toBe("PDF");
  expect(root.querySelector("button.chatpdf-chip-title")?.textContent).toBe("Paper");
  const button = more(); button.focus();
  refreshSourceChips(root);
  expect(more()).toBe(button); expect(document.activeElement).toBe(button);
});
it("replaces removed source rows and persists removal while aborting its active read", async () => {
  const old = mocks.state.session.addSource("PDF", "Old", undefined, 1);
  refreshSourceChips(root); const previous = more();
  mocks.state.session.removeSource(old.id);
  const replacement = mocks.state.session.addSource("PDF", "New", undefined, 1);
  refreshSourceChips(root);
  expect(previous.isConnected).toBe(false);
  const abort = vi.fn();
  mocks.state.backgroundStreams.set(mocks.state.session.id, { abortController: { abort } });
  more().click();
  const remove = [...root.querySelectorAll<HTMLButtonElement>('[role="menuitem"]')].find(button => /Remove|移除/.test(button.textContent || ""))!;
  remove.click();
  expect(mocks.state.session.getSource(replacement.id)).toBeUndefined();
  expect(abort).toHaveBeenCalledOnce();
  expect(saveSession).toHaveBeenCalledWith(expect.objectContaining({ sources: [] }));
});
it("keeps a source menu stable across refresh and dismisses it with the keyboard", () => {
  mocks.state.session.addSource("PDF", "Paper", undefined, 1); refreshSourceChips(root);
  const chip = root.querySelector(".chatpdf-source-chip")!;
  chip.dispatchEvent(new MouseEvent("contextmenu", { bubbles: true, cancelable: true }));
  const menu = root.querySelector(".chatpdf-source-menu")!;
  refreshSourceChips(root); expect(root.querySelector(".chatpdf-source-chip")).toBe(chip);
  document.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
  expect(menu.isConnected).toBe(false);
});
